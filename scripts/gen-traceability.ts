// Generates docs/release/traceability.md from the threat model and docs/release/traceability.json (so the table cannot drift by hand).
// Usage: npm run gen:traceability   (tests/unit/traceability.test.ts checks the committed file and that every referenced test/control exists)
import { readFileSync, writeFileSync } from "node:fs";

const tm = readFileSync("docs/threat-model.md", "utf8");
const rows = [...tm.matchAll(/^\| ((?:T|AB)-\d+) \| ([^|]*) \| ([^|]*) \|/gm)];
const { map } = JSON.parse(readFileSync("docs/release/traceability.json", "utf8")) as { map: Record<string, Array<[string, string]>> };
const out = ["# Threat model traceability", "",
  "Generated by `npm run gen:traceability` from `docs/threat-model.md` and `docs/release/traceability.json`. Each row lists where the control is proven.",
  "`tests/unit/traceability.test.ts` checks that every row has at least one mapped test or CI control, that each file exists and contains the named phrase.",
  "The unit test proves the proof EXISTS; whether it PASSES is shown by the test and CI reports (`docs/release/test-and-scan-report.md`). Nothing here is a certification.", "",
  "| ID | Threat (see threat model) | Where it is proven |", "|---|---|---|"];
for (const m of rows) {
  const id = m[1]!; const refs = map[id] ?? [];
  const title = ((id.startsWith("T-") ? m[3] : m[2]) ?? "").trim().replace(/\|/g, "/").slice(0, 110);
  out.push(`| ${id} | ${title} | ${refs.map(([f, p]) => `\`${f}\` — "${p}"`).join("<br>")} |`);
}
writeFileSync("docs/release/traceability.md", out.join("\n") + "\n");
console.log(`wrote docs/release/traceability.md (${rows.length} rows)`);
